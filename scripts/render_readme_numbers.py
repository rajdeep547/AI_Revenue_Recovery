"""Slice 11-12 -- render every hand-checkable number in the docs from source,
between the generated-numbers markers, and verify no doc has drifted.

Sources (this script INVENTS no numbers):
  * results/final_run.json            (STEP 1, full 2,000-event run, locked 70:30)
  * results/split_comparison_500.json (STEP 2, first-500-customer split sweep)
  * the pytest collection count        (`pytest --collect-only -q`)

Covered docs:
  * README.md       -- the headline corpus table + sensitivity sweep
  * EVALUATION.md   -- the quotable verdict sentence + the evidence table
  * ARCHITECTURE.md -- the structural counts (events -> customers -> decisions,
                       guardrail-evaluation rows, test count)

Every value is read straight from those sources and formatted with fixed
precision so the output is byte-stable.

Modes
-----
  python scripts/render_readme_numbers.py            # --check (default)
  python scripts/render_readme_numbers.py --check    # exit 1 if any doc drifted
  python scripts/render_readme_numbers.py --write     # splice fresh blocks in

CI runs `--check`: it re-derives each block from source and fails the build if
what is committed between the markers differs by a single byte. Regenerate with
`--write` and commit the docs alongside the artifacts.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
README = REPO / "README.md"
EVALUATION = REPO / "EVALUATION.md"
ARCHITECTURE = REPO / "ARCHITECTURE.md"
FINAL = REPO / "results" / "final_run.json"
SPLIT = REPO / "results" / "split_comparison_500.json"

BEGIN = "<!-- BEGIN GENERATED NUMBERS -->"
END = "<!-- END GENERATED NUMBERS -->"


# ------------------------------------------------------------------ test count
def test_count() -> int:
    """The number pytest collects -- re-derived, never hard-coded. Collection
    only (no execution); ~0.4 s."""
    out = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q"],
        cwd=REPO, capture_output=True, text=True,
    )
    m = re.search(r"(\d+)\s+tests?\s+collected", out.stdout + out.stderr)
    if not m:
        raise SystemExit(
            "STOP: could not read the pytest collection count from\n"
            + (out.stdout + out.stderr)[-2000:]
        )
    return int(m.group(1))


# ------------------------------------------------------------------ formatting
def inr(x: float) -> str:
    """`479834.0` -> `479,834.00` (Indian-file uses plain thousands here)."""
    return f"{x:,.2f}"


def pp(x: float) -> str:
    """percentage-point value already in pp units -> 2 dp."""
    return f"{x:.2f}"


def pct(rate: float) -> str:
    """proportion in [0,1] -> percent, 2 dp."""
    return f"{rate * 100:.2f}"


def short_sha(h: str) -> str:
    return h[:8]


def d6(x: float) -> str:
    """6-decimal fixed -- for the uplift / CI figures quoted to full precision."""
    return f"{x:.6f}"


