        f"decisions** (`process_failure` is idempotent per `payment_id`), of "
        f"which **{n_act:,} reached ACT** and walked the guardrail ladder, "
        f"writing **{n_guardrail_rows:,} `guardrail_evaluations` rows** "
        f"(7 per rung attempted, never collapsed). "
        f"Arm assignment splits those {n_customers:,} customers "
        f"{cl['n_treatment_customers']:,} treatment / "
